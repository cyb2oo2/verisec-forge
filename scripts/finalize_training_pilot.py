"""Record assistant audit observations and quarantine their training components.

Observations are authored by the current assistant, not generated by this script.
No validation/test decisions are inspected or changed.
"""
import json
from collections import Counter
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'src'))
from vrf.training_dataset import sha, orientations, validate_splits


def main():
    report = ROOT/'reports/scientific_review_2026_09_07/p1'
    out = ROOT/'data/processed/patcheval_training_pilot_v1'
    release_path = report/'training_pilot_v1_release.json'
    audit_path = report/'training_pilot_v1_ai_audit.json'
    train_path = out/'train_released.jsonl'
    if any(p.exists() for p in [release_path,audit_path,train_path]):
        raise FileExistsError('Refusing to overwrite pilot release')
    load = lambda p: json.loads(p.read_text(encoding='utf-8'))
    base_path = report/'training_pilot_v1.json'
    manifest = load(base_path)
    for path,expected in manifest['artifact_sha256'].items():
        if sha((ROOT/path).read_bytes())!=expected:raise ValueError('candidate dataset drift')
    selection_path = report/'training_pilot_v1_audit_selection.json'
    selection = load(selection_path)
    splits = load(out/'PRIVATE_pairs.json')
    train = {p['pair_key']:p for p in splits['train']}
    # Reproduce selection, rather than trusting arbitrary audit IDs.
    expected = sorted(train,key=lambda k:sha(('audit-v1'+k).encode()))[:12]
    if selection != expected:raise ValueError('audit selection drift')
    observations = [
        ('suspected_repair_defect','after',95,108,'members is a dict but iteration supplies keys to ban_user; stale user_id is also used for bookkeeping. Missing helper contract prevents confirming repaired safety.'),
        ('needs_context','before',66,84,'Auth parsing and encoding change requires toString serialization and caller trust boundary; raw auth fields alone do not certify an exploit.'),
        ('needs_context','before',70,86,'Storage helpers and token comparison change together; their implementations and session binding are missing.'),
        ('needs_context','after',31,37,'ImportedDump gets an extra filter, but field provenance, filter semantics and exposure route are not shown.'),
        ('needs_context','before',14,31,'Both paths use escaping; dialect syntax changes do not by themselves prove that one candidate is vulnerable.'),
        ('needs_context','before',12,23,'Broader permission predicate guards support export; role mapping and contents are needed to establish confidentiality impact.'),
        ('needs_context','before',2,5,'Missing option terminator is suspicious, but ValidateURL may already reject option-like strings and runcmd behavior is absent.'),
        ('shared_risk','after',7,12,'Both variants test HasPrefix(allowlistEntry, requestedOrg), allowing org abc for entry abcdef/* under ordinary organization semantics. Changing only empty-list policy does not repair this prefix mismatch.'),
        ('needs_context','after',2,3,'Before embeds key_name in SQL; after parameterizes but prepends its parameter before any lhs parameters. SQL compiler ordering and attacker control require verification.'),
        ('needs_context','before',2,6,'Prototype-property recursion is suspicious; isObject and mixinDeep behavior are needed to assess the actual pollution paths and completeness of the fix.'),
        ('needs_context','after',42,59,'New rsync argument validator and insertion position affect safety; its implementation and accepted command shape are absent.'),
        ('needs_context','before',3,8,'Only update-success bookkeeping changes. A security consequence requires the endpoint-label updater and observer retry behavior.')]
    audit_rows=[]
    for key,(status,side,start,end,note) in zip(selection,observations,strict=True):
        p=train[key]
        if not 1<=start<=end<=len(p[side].splitlines()):raise ValueError('audit evidence range')
        audit_rows.append(dict(pair_key=key,status=status,source_side=side,start_line=start,end_line=end,
                               input_sha256=sha(json.dumps([p['before'],p['after']],ensure_ascii=False).encode()),
                               observation=note,label_promoted_to_gold=False))
    held={train[k]['component_id'] for k in selection}
    quarantine=[p for p in splits['train'] if p['component_id'] in held]
    splits['train']=[p for p in splits['train'] if p['component_id'] not in held]
    validate_splits(splits)
    audit=dict(annotation_source='current_assistant',execution_mode='existing_conversation',
        independent_blind_review=False,upstream_direction_visible=True,
        reading_scope='Displayed source and targeted change review; helpers and upstream execution not verified',
        observed_pairs=len(audit_rows),quarantined_components=len(held),quarantined_pairs=len(quarantine),
        selection_sha256=sha(selection_path.read_bytes()),parent_manifest_sha256=sha(base_path.read_bytes()),
        policy='Conservatively reserve every audited component from training; this does not prove all reserved pairs invalid or unreviewed pairs correct.',
        statuses=dict(Counter(r['status'] for r in audit_rows)),rows=audit_rows)
    audit_path.write_text(json.dumps(audit,indent=2)+'\n',encoding='utf-8')
    rows=[r for p in splits['train'] for r in orientations(p)]
    train_path.write_text(''.join(json.dumps(r,ensure_ascii=False)+'\n' for r in rows),encoding='utf-8')
    ledger=out/'PRIVATE_released_pairs.json'
    ledger.write_text(json.dumps(splits,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    quarantine_path=out/'audit_quarantine.json'
    quarantine_path.write_text(json.dumps([p['pair_key'] for p in quarantine],indent=2)+'\n',encoding='utf-8')
    manifest['datasets']['train']=train_path.relative_to(ROOT).as_posix()
    p=splits['train']
    manifest['splits']['train']=dict(pairs=len(p),rows=2*len(p),projects=len({x['project'] for x in p}),
        cves=len({x['cve'] for x in p}),components=len({x['component_id'] for x in p}),max_tokens=max(x['max_tokens'] for x in p))
    cfg=load(ROOT/'configs/dataset_expansion_v1.json')
    manifest['gates']={s:manifest['splits'][s]['pairs']>=cfg['minimum_pairs'][s] and manifest['splits'][s]['projects']>=cfg['minimum_projects'][s] for s in splits}
    manifest['status']='READY_FOR_WEAK_SUPERVISION_PILOT' if all(manifest['gates'].values()) else 'INSUFFICIENT_PILOT_DATA'
    manifest['retained_pairs']=sum(len(ps) for ps in splits.values())
    manifest['ai_audit_observed_pairs']=12
    manifest['audit_quarantined_pairs']=len(quarantine)
    for p in [base_path,audit_path,selection_path,train_path,ledger,quarantine_path]:
        manifest['artifact_sha256'][p.relative_to(ROOT).as_posix()]=sha(p.read_bytes())
    manifest['release_policy']='12 training-pair AI observations led to whole-component quarantine. Remaining labels are unverified upstream weak supervision. Validation/test membership unchanged; no semantic validation claim.'
    release_path.write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
    print(json.dumps({k:manifest[k] for k in ['status','retained_pairs','splits','audit_quarantined_pairs','gates']},indent=2))


if __name__=='__main__':main()
